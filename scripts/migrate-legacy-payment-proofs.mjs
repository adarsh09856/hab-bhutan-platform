import { createHash } from 'node:crypto';
import { constants } from 'node:fs';
import { chmod, copyFile, lstat, mkdir, readFile, readdir, unlink } from 'node:fs/promises';
import path from 'node:path';

const mode = process.argv[2];
if (!['--dry-run', '--stage', '--seal'].includes(mode)) {
  throw new Error('Usage: node scripts/migrate-legacy-payment-proofs.mjs --dry-run|--stage|--seal');
}

const root = process.cwd();
const destinationDir = path.join(root, '.data', 'private-uploads', 'payment-proofs', 'legacy');
const sources = [path.join(root, 'public', 'uploads'), path.join(root, 'public', 'uploads', 'slips')];
const namePattern = /^(?:hab|slip)-\d{13}-\d{4}\.(?:jpg|png|webp|gif|pdf)$/i;
let found = 0;
let staged = 0;
let sealed = 0;

for (const sourceDir of sources) {
  const entries = await readdir(sourceDir, { withFileTypes: true }).catch((error) => {
    if (error.code === 'ENOENT') return [];
    throw error;
  });
  for (const entry of entries) {
    if (!entry.isFile() || !namePattern.test(entry.name)) continue;
    // Names are generated by the old public proof-upload routes; other media is untouched.
    if ((sourceDir.endsWith(`${path.sep}slips`)) !== entry.name.startsWith('slip-')) continue;
    found += 1;
    if (mode === '--dry-run') continue;
    const from = path.join(sourceDir, entry.name);
    const to = path.join(destinationDir, entry.name);
    if (!(await lstat(from)).isFile()) throw new Error('Proof source changed during migration.');
    await mkdir(destinationDir, { recursive: true, mode: 0o700 });
    try { await copyFile(from, to, constants.COPYFILE_EXCL); } catch (error) {
      if (error.code !== 'EEXIST') throw error;
    }
    await chmod(to, 0o600);
    const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
    if (digest(await readFile(from)) !== digest(await readFile(to))) {
      throw new Error('Private proof copy mismatch; original was preserved.');
    }
    staged += 1;
    if (mode === '--seal') {
      await unlink(from);
      sealed += 1;
    }
  }
}
console.log(`Legacy payment proofs: ${found} matched, ${staged} verified private copies, ${sealed} public originals sealed.`);
